#pragma once
#include <string>
#include <vector>
#include "Item.h"

// ================================================================================
// [ Inventory.h / Inventory.cpp ]  -  인벤토리 & 합성 시스템
// 담당: (인벤토리 / 상점)
//
// 이 파일이 하는 일
//   1) 플레이어가 들고 있는 아이템을 관리 (추가/제거/조회, 최대 30개 제한)
//   2) 재료 아이템을 조합해서 새 아이템을 만드는 "합성" 기능 제공
//
// 다른 팀원이 알아야 할 것
//   - Player.h        : Player 클래스가 멤버로 `Inventory inventory;` 를 들고 있음.
//                        즉 어디서든 `player.inventory.함수이름()` 형태로 호출하면 됨.
//   - battle.cpp/monster.cpp : 몬스터 처치 시 `player.inventory.AddItem(드랍아이템, 개수)` 호출해서
//                        전리품을 인벤토리에 넣어주면 됨. 30개 꽉 차면 자동으로 초과분은 버려짐.
//   - Shop.cpp         : 구매 시 AddItem(), 판매 시 RemoveItem()/HasItem()/FindItem() 사용.
//   - UI.cpp           : GetItems()로 (아이템, 개수) 목록을 받아서 화면에 그리면 됨.
//                        아이템 정보는 item.GetName(), item.GetPrice() 등 Item.h의 getter로 꺼내 씀.
//
// 새 레시피를 추가하고 싶다면?
//   -> 이 파일은 건드릴 필요 없고, Inventory.cpp 맨 위 recipeList 벡터에 한 줄만 추가하면 됨.
//      (자세한 형식은 Inventory.cpp 상단 주석 참고)
// ================================================================================

// --------------------------------------------------------------------------------
// [Recipe] 합성 레시피 하나를 표현하는 구조체
//
//   result      : 합성 성공 시 얻는 완성 아이템 (Item 객체 그대로)
//   ingredients : 필요한 재료 목록. { {"재료 아이템 이름", 필요 개수}, ... } 형태의 리스트.
//                 재료 이름은 반드시 인벤토리에 실제로 들어올 수 있는 아이템의 GetName()과
//                 정확히 일치해야 함 (몬스터 드랍템, 상점 판매 아이템 등).
//
// 예) 고철 조각 3개 + 캔 1개를 합쳐서 "녹슨 방패"를 만드는 레시피:
//     Recipe{
//         Item("녹슨 방패", "고철로 만든 투박한 방패", "방패로 막아낸다!",
//              ItemRarity::B, {}, {}, 15, 80),
//         { {"고철 조각", 3}, {"캔", 1} }
//     }
// --------------------------------------------------------------------------------
struct Recipe {
    Item result;                                          // 합성 결과 아이템
    std::vector<std::pair<std::string, int>> ingredients;  // (재료 이름, 필요 개수) 목록
};

// Player.h가 Inventory.h를 include하기 때문에 여기서 Player.h를 include하면
// 순환 include가 됨. 그래서 포인터/참조만 필요한 시점까지는 전방 선언만 해둠.
class Player;

// --------------------------------------------------------------------------------
// [UseResult] 소비 아이템 사용 시도 결과
//   SUCCESS        : 사용 성공 (효과 적용 + 아이템 1개 소모됨)
//   NOT_FOUND      : 인벤토리에 그 이름의 아이템이 없음
//   NOT_CONSUMABLE : 아이템은 있지만 소비 아이템이 아님 (무기류라 "사용" 개념이 없음)
// --------------------------------------------------------------------------------
enum class UseResult {
    SUCCESS,
    NOT_FOUND,
    NOT_CONSUMABLE
};

// ================================================================================
// [Inventory] 캐릭터가 소지한 아이템을 관리하는 클래스
//
// 내부적으로 std::vector<std::pair<Item, int>> 로 관리함.
//   - pair.first  = 아이템 정보 (Item)
//   - pair.second = 그 아이템을 몇 개 들고 있는지 (int)
// 같은 이름의 아이템은 슬롯을 새로 만들지 않고 기존 슬롯의 개수만 늘어남.
//
// 사용 예시 (다른 팀원 코드에서):
//     player.inventory.AddItem(dropItem, 1);              // 몬스터 드랍템 획득
//     if (player.inventory.HasItem("포션", 2)) { ... }     // 포션 2개 있는지 체크
//     player.inventory.RemoveItem("포션", 1);              // 포션 1개 소모
// ================================================================================
class Inventory {
public:
    // ----------------------------------------------------------------------------
    // 인벤토리 최대 소지 개수 (전체 아이템 개수의 "합"이 기준. 종류 수/슬롯 수 아님)
    // 예) 포션 10개 + 검 5개 + 방패 15개 = 총 30개 → 꽉 찬 상태
    // 값을 바꾸고 싶으면 여기 숫자만 수정하면 게임 전체에 반영됨.
    // ----------------------------------------------------------------------------
    static const int MAX_ITEM_COUNT = 30;

    Inventory();

    // ------------------------------------------------------------------
    // AddItem(item, count)
    //   아이템을 인벤토리에 추가한다.
    //   - 이미 같은 이름의 아이템이 있으면 개수만 증가시킴 (새 슬롯 안 만듦)
    //   - 처음 들어오는 아이템이면 새 슬롯을 만들어서 추가함
    //   - 인벤토리가 이미 꽉 찼거나(30/30), 추가하려는 개수가 남은 공간보다 많으면
    //     "들어갈 수 있는 만큼만" 넣고 나머지는 버림 (콘솔에 안내 메시지 자동 출력됨)
    //
    //   매개변수:
    //     item  - 추가할 아이템 정보
    //     count - 추가할 개수 (기본값 1)
    //
    //   반환값:
    //     실제로 인벤토리에 들어간 개수. count와 다를 수 있음(공간 부족 시).
    //     0이면 하나도 못 들어간 것 (인벤토리가 이미 가득 참).
    //     ※ 반환값을 안 받고 그냥 호출만 해도 동작에는 문제없음 (몬스터 드랍 등).
    //
    //   호출 예) player.inventory.AddItem(potionItem, 3);
    // ------------------------------------------------------------------
    int AddItem(const Item& item, int count = 1);

    // ------------------------------------------------------------------
    // RemoveItem(itemName, count)
    //   이름으로 아이템을 찾아서 지정한 개수만큼 제거한다.
    //   제거 후 개수가 0이 되면 슬롯 자체를 인벤토리에서 없앤다.
    //
    //   매개변수:
    //     itemName - 제거할 아이템 이름 (Item::GetName()과 정확히 일치해야 함)
    //     count    - 제거할 개수 (기본값 1)
    //
    //   반환값:
    //     true  - 정상적으로 제거됨
    //     false - 아이템이 없거나(인벤토리에 없음), 보유 개수보다 많이 지우려고 함
    //             (이 경우 아무것도 지워지지 않음 - 일부만 지워지는 일은 없음)
    //
    //   주의: 실제로 제거되는지 모른 채 호출하면 안 되는 로직(합성 재료 소모 등)에서는
    //         반드시 먼저 HasItem()으로 확인하거나 반환값을 체크할 것.
    // ------------------------------------------------------------------
    bool RemoveItem(const std::string& itemName, int count = 1);

    // ------------------------------------------------------------------
    // UseItem(itemName, player)
    //   소비 아이템(ItemCategory::CONSUMABLE)을 사용해서 효과를 player에게 적용하고
    //   아이템을 1개 소모한다.
    //
    //   처리 순서:
    //     1) 인벤토리에서 itemName을 찾는다 -> 없으면 NOT_FOUND
    //     2) 찾은 아이템이 CONSUMABLE이 아니면(무기류) -> NOT_CONSUMABLE (아무 변화 없음)
    //     3) 아이템의 효과(healHP, buffMaxHP, buffATK, gainLevel)를 player에 적용
    //     4) 아이템을 인벤토리에서 1개 제거 -> SUCCESS
    //
    //   ※ 데모 버전 주의: 실제 Player.h(캐릭터 담당)가 오기 전까지 player.hp/maxHp/atk는
    //      임시 필드임. isPermanent가 false인(일시적) 버프도 이 데모에는 전투 시스템이
    //      없어서 "지속시간이 끝나면 원래대로" 로직은 아직 없음 - 실제 전투 시스템과
    //      연동할 때 buffATK 적용 방식을 isPermanent 기준으로 분기해줘야 함.
    //
    //   반환값: UseResult (위 enum 참고)
    //
    //   호출 예) player.inventory.UseItem("체력 물약", player);
    // ------------------------------------------------------------------
    UseResult UseItem(const std::string& itemName, Player& player);

    // ------------------------------------------------------------------
    // HasItem(itemName, count)
    //   해당 아이템을 지정한 개수 "이상" 보유하고 있는지 확인만 한다 (변경 없음).
    //
    //   반환값: true(충분히 있음) / false(부족하거나 아예 없음)
    //
    //   호출 예) 전투에서 소모품을 쓰기 전에:
    //     if (player.inventory.HasItem("치료 물약", 1)) { ... 사용 ... }
    // ------------------------------------------------------------------
    bool HasItem(const std::string& itemName, int count = 1) const;

    // ------------------------------------------------------------------
    // FindItem(itemName)
    //   이름으로 아이템의 상세 정보(Item 전체)를 조회한다.
    //   개수가 아니라 "그 아이템이 어떤 아이템인지"(공격력, 등급, 설명 등)가 필요할 때 사용.
    //
    //   반환값: 찾으면 해당 Item의 포인터, 없으면 nullptr
    //   주의: 반드시 nullptr 체크 후 사용할 것 (없는 아이템이면 크래시 남)
    //
    //   호출 예) 전투에서 아이템 공격력을 가져올 때:
    //     const Item* item = player.inventory.FindItem("녹슨 검");
    //     if (item) { int atk = item->GetBaseATK(); }
    // ------------------------------------------------------------------
    const Item* FindItem(const std::string& itemName) const;

    // ------------------------------------------------------------------
    // GetItemCount(itemName)
    //   해당 아이템을 정확히 몇 개 갖고 있는지 개수만 조회한다.
    //   반환값: 보유 개수 (없으면 0)
    // ------------------------------------------------------------------
    int GetItemCount(const std::string& itemName) const;

    // ------------------------------------------------------------------
    // GetItems()
    //   인벤토리 전체 목록을 (아이템, 개수) 쌍의 리스트로 반환한다.
    //   UI.cpp에서 인벤토리 화면을 그릴 때 이 함수로 목록을 받아서 순회하면 됨.
    //
    //   호출 예)
    //     for (const auto& slot : player.inventory.GetItems()) {
    //         const Item& item = slot.first;
    //         int count = slot.second;
    //         // 화면에 item.GetName(), count 등을 출력
    //     }
    // ------------------------------------------------------------------
    const std::vector<std::pair<Item, int>>& GetItems() const;

    // ------------------------------------------------------------------
    // GetTotalItemCount()
    //   인벤토리에 들어있는 "모든 아이템 개수의 합"을 반환한다. (종류 수 아님)
    //   예) 포션 x3, 검 x2 이면 -> 5 반환
    //   UI 상단에 "인벤토리 12/30" 같은 걸 표시할 때 사용.
    // ------------------------------------------------------------------
    int GetTotalItemCount() const;

    // ------------------------------------------------------------------
    // GetRemainingSpace()
    //   인벤토리에 몇 개 더 들어갈 수 있는지 (MAX_ITEM_COUNT - 현재 총 개수).
    //   상점에서 구매 전 "공간 있는지" 미리 체크할 때 유용함.
    //   (Shop::Buy()가 실제로 이 함수로 구매 가능 여부를 판단함)
    // ------------------------------------------------------------------
    int GetRemainingSpace() const;

    // ================== 합성(Crafting) 관련 함수 ==================

    // ------------------------------------------------------------------
    // CanCraft(resultName)
    //   resultName이라는 이름의 아이템을 "지금 당장" 합성할 수 있는지 확인한다.
    //   - 해당 이름의 레시피가 존재하는지
    //   - 그 레시피가 요구하는 재료를 전부 필요한 개수만큼 갖고 있는지
    //   둘 다 만족해야 true.
    //
    //   반환값: true(합성 가능) / false(레시피 없음 또는 재료 부족)
    // ------------------------------------------------------------------
    bool CanCraft(const std::string& resultName) const;

    // ------------------------------------------------------------------
    // Craft(resultName)
    //   실제로 합성을 수행한다.
    //   1) CanCraft()로 가능 여부 확인 (안 되면 즉시 false 반환, 아무 변화 없음)
    //   2) 레시피에 필요한 재료들을 인벤토리에서 전부 소모(RemoveItem)
    //   3) 완성된 결과 아이템을 인벤토리에 추가(AddItem)
    //
    //   반환값: true(합성 성공) / false(재료 부족이나 레시피 없음 - 아무것도 소모되지 않음)
    //
    //   호출 예) player.inventory.Craft("녹슨 방패");
    // ------------------------------------------------------------------
    bool Craft(const std::string& resultName);

    // ------------------------------------------------------------------
    // GetCraftableList()
    //   현재 가진 재료로 합성 가능한 아이템 "이름" 목록을 전부 반환한다.
    //   UI에서 "지금 합성 가능한 것들만" 강조 표시하고 싶을 때 사용.
    // ------------------------------------------------------------------
    std::vector<std::string> GetCraftableList() const;

    // ------------------------------------------------------------------
    // Show() / ShowRecipes()
    //   콘솔에 인벤토리/레시피 목록을 텍스트로 출력하는 임시 디버그용 함수.
    //   UI.cpp가 실제 화면(콘솔 UI든 그래픽 UI든)을 완성하면 이 함수들은
    //   더 이상 안 쓰이거나 디버그 로그용으로만 남겨도 됨. 삭제해도 다른 코드에
    //   영향 없음 (GetItems(), GetCraftableList() 등으로 UI가 직접 그리면 되기 때문).
    // ------------------------------------------------------------------
    void Show() const;
    void ShowRecipes() const;

private:
    std::vector<std::pair<Item, int>> items; // (아이템, 보유 개수) 목록. 종류별로 슬롯 하나씩.
};

// ------------------------------------------------------------------
// GetCraftingRecipes()
//   게임에 등록된 전체 합성 레시피 목록을 조회하는 전역 함수.
//   UI.cpp에서 "합성 화면"을 그릴 때 이 함수로 전체 레시피를 받아서
//   하나씩 보여주고, 사용자가 고르면 Inventory::Craft(이름)을 호출하면 됨.
//   실제 레시피 데이터는 Inventory.cpp 맨 위 recipeList에서만 관리함
//   (여기 Inventory.h는 건드릴 필요 없음).
// ------------------------------------------------------------------
const std::vector<Recipe>& GetCraftingRecipes();
