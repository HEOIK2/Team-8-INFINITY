// ============================================================================
#include "UI.h"
#include "GameText.h"

#include <iostream>   // std::cout, std::cin
#include <limits>     // std::numeric_limits (입력 버퍼 비울 때 사용)

// #ifdef _WIN32 : Windows 에서 컴파일할 때만 아래 줄을 포함합니다.
// windows.h 는 Mac/Linux 에 없으므로 무조건 include 하면 그쪽에서 에러납니다.
// 우리 팀은 전원 Visual Studio 이지만, 습관으로 감싸두는 게 안전합니다.
#ifdef _WIN32
#include <windows.h>
#endif

namespace UI {

    // ----------------------------------------------------------------------------
    //  Init : 콘솔 인코딩 설정
    // ----------------------------------------------------------------------------
    //  Windows 콘솔의 기본 코드페이지는 949(한국어 완성형)입니다.
    //  우리 소스는 UTF-8 이라 그대로 두면 글자가 깨집니다.
    //    SetConsoleOutputCP → 출력용. 로고 █ 와 한글이 제대로 나옴
    //    SetConsoleCP       → 입력용. 한글 이름을 입력받을 때 필요
    //  ★ 둘 다 해야 합니다. 하나만 하면 출력 또는 입력 한쪽이 깨집니다.
    // ----------------------------------------------------------------------------
    void Init() {
#ifdef _WIN32
        SetConsoleOutputCP(CP_UTF8);
        SetConsoleCP(CP_UTF8);
#endif
    }

    // ----------------------------------------------------------------------------
    //  Clear : 화면 지우기
    // ----------------------------------------------------------------------------
    //  system() 은 OS 명령어를 실행합니다. 느리고 보안상 권장되진 않지만
    //  콘솔 과제 수준에서는 가장 간단하고 확실한 방법입니다.
    // ----------------------------------------------------------------------------
    void Clear() {
#ifdef _WIN32
        system("cls");
#else
        system("clear");
#endif
    }

    // ----------------------------------------------------------------------------
    //  Line : 구분선 출력
    // ----------------------------------------------------------------------------
    //  std::string(width, ch) → 문자 ch 를 width 번 반복한 문자열을 만듭니다.
    //    예) std::string(5, '=') 는 "=====" 
    //  ★ UI.h 에 기본값을 썼으므로 여기서는 다시 쓰지 않습니다.
    // ----------------------------------------------------------------------------
    void Line(char ch, int width) {
        std::cout << std::string(width, ch) << '\n';
    }

    // ----------------------------------------------------------------------------
    //  Header : 제목 블록 출력
    // ----------------------------------------------------------------------------
    void Header(const std::string& title) {
        Line('=');
        std::cout << "              < " << title << " >\n";
        Line('-');
    }

    // ----------------------------------------------------------------------------
    //  Print / PrintLog : 문자열 출력
    // ----------------------------------------------------------------------------
    //  '\n' 과 std::endl 의 차이:
    //    std::endl 은 줄바꿈 + 버퍼 강제 비우기(flush)를 합니다. 그래서 느립니다.
    //    콘솔 게임에서는 '\n' 으로 충분합니다.
    // ----------------------------------------------------------------------------
    void Print(const std::string& text) {
        std::cout << text << '\n';
    }

    void PrintLog(const std::string& text) {
        std::cout << "  " << text << '\n';   // 앞 공백 2칸 = 로그 들여쓰기
    }

    // ----------------------------------------------------------------------------
    //  DrawTitle : 타이틀 화면
    // ----------------------------------------------------------------------------
    void DrawTitle() {
        Clear();
        std::cout << GameText::TITLE_LOGO;   // 로고 안에 이미 개행이 있어 \n 불필요
        std::cout << GameText::TITLE_MENU;
        Line('=');
    }

    // ----------------------------------------------------------------------------
    //  AskChoice : 숫자 메뉴 입력  ★이 함수의 원리는 꼭 이해하고 넘어가세요★
    // ----------------------------------------------------------------------------
    //  [문제 1] 사용자가 숫자 대신 'a' 를 입력하면?
    //    std::cin >> choice 가 실패하고, cin 이 "실패(fail) 상태"로 굳습니다.
    //    이 상태에서는 이후 모든 입력 시도가 즉시 실패합니다.
    //    → while 루프가 입력을 기다리지 않고 무한히 돌면서 화면이 폭주합니다.
    //    이걸 푸는 게 std::cin.clear() 입니다. (실패 표시를 지움)
    //
    //  [문제 2] clear() 만 하면?
    //    입력 버퍼에 'a' 가 그대로 남아 있어서 다음 시도도 또 실패합니다.
    //    → cin.ignore(...) 로 버퍼에 남은 글자를 개행까지 통째로 버립니다.
    //    numeric_limits<streamsize>::max() 는 "개수 제한 없이" 라는 뜻입니다.
    //
    //  [문제 3] 숫자를 제대로 입력해도 문제가 있습니다.
    //    "1" 을 입력하면 >> 는 1만 가져가고 Enter(개행)는 버퍼에 남습니다.
    //    바로 다음에 std::getline 으로 이름을 받으면 그 개행을 읽고
    //    이름이 "빈 문자열"로 통과해 버립니다.
    //    → 그래서 "성공한 경우에도" ignore 를 한 번 해줍니다. (아래 return 직전)
    // ----------------------------------------------------------------------------
    int AskChoice(int minV, int maxV) {
        int choice = 0;

        while (true) {
            std::cout << GameText::MSG_PROMPT;

            // cin >> 의 결과를 조건문에 바로 넣으면 "입력 성공 여부"로 평가됩니다.
            // 성공 && 범위 안 → 통과
            if (std::cin >> choice && choice >= minV && choice <= maxV) {
                std::cin.ignore(std::numeric_limits<std::streamsize>::max(), '\n');
                return choice;
            }

            // 실패했거나 범위를 벗어난 경우: 상태 복구 후 재시도
            std::cin.clear();  // 실패 표시 해제
            std::cin.ignore(std::numeric_limits<std::streamsize>::max(), '\n'); // 찌꺼기 버리기
            Print(GameText::MSG_INVALID);
        }
    }

    // ----------------------------------------------------------------------------
    //  AskName : 이름 입력 (공백 방어)
    // ----------------------------------------------------------------------------
    //  std::cin >> name 을 쓰지 않고 std::getline 을 쓰는 이유:
    //    >> 는 공백에서 끊어서 "홍 길동" 을 입력하면 "홍" 만 들어옵니다.
    //    getline 은 Enter 까지 한 줄 전체를 읽습니다.
    //
    //  find_first_not_of(" \t") :
    //    공백과 탭이 아닌 첫 글자의 위치를 찾습니다.
    //    그런 글자가 하나도 없으면 npos(= 못 찾음) 를 반환합니다.
    //    즉 결과가 npos → 공백/탭으로만 이루어진 입력이라는 뜻.
    // ----------------------------------------------------------------------------
    std::string AskName() {
        std::string name;

        while (true) {
            std::cout << GameText::MSG_ASK_NAME;
            std::getline(std::cin, name);

            bool blank = name.empty();                 // 그냥 Enter만 친 경우
            if (!blank) {
                blank = (name.find_first_not_of(" \t") == std::string::npos); // 공백만 친 경우
            }

            if (!blank) {
                return name;   // 정상 입력
            }
            Print(GameText::MSG_EMPTY_NAME);
        }
    }

    // ----------------------------------------------------------------------------
    //  Pause : Enter 대기
    // ----------------------------------------------------------------------------
    //  cin.get() 은 글자 하나(여기서는 Enter)를 읽을 때까지 멈춥니다.
    //  ★ 직전에 AskChoice 를 쓰지 않고 곧바로 Pause 를 부르면
    //    버퍼에 남은 개행을 먹고 그냥 지나갈 수 있습니다.
    //    AskChoice 가 개행을 정리해 두므로 보통은 정상 동작합니다.
    // ----------------------------------------------------------------------------
    void Pause() {
        Print(GameText::MSG_PAUSE);
        std::cin.get();
    }

} // namespace UI