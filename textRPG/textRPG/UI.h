#pragma once
// ============================================================================
//  UI.h  —  콘솔 출력/입력 담당 (선언부)
// ============================================================================
//  [이 파일의 역할]
//    "어떻게 보여줄까"와 "입력을 어떻게 안전하게 받을까"만 담당합니다.
//
//  [★ 절대 규칙 — 반드시 지켜주세요 ★]
//    이 파일에서 Player.h / Monster.h / Item.h 를 #include 하지 마세요.
//
//    이유:
//      UI가 게임 클래스를 알게 되면, 그 클래스가 아직 미완성일 때
//      UI까지 컴파일이 안 됩니다. 그러면 아무도 실행을 못 합니다.
//      UI는 int, std::string 같은 "값"만 받도록 유지합니다.
//
//    예) 상태창을 출력하고 싶다면
//        DrawStatus(const Player& p)          ← 금지
//        DrawStatus(name, lv, hp, maxHp, atk) ← 이렇게
// ============================================================================

#include <string>   // std::string 사용을 위해 필요 (표준 헤더는 OK)

namespace UI {

    // ------------------------------------------------------------------
    //  초기화 / 화면
    // ------------------------------------------------------------------

    // 콘솔을 UTF-8 모드로 전환합니다.
    // ★ main() 의 가장 첫 줄에서 딱 한 번 호출하세요.
    //   이거 안 하면 로고의 █ 문자와 한글이 ??? 로 깨집니다.
    void Init();

    // 화면을 지웁니다. (Windows: cls / Mac·Linux: clear)
    void Clear();

    // ------------------------------------------------------------------
    //  출력
    // ------------------------------------------------------------------

    // 타이틀 로고 + 시작/종료 메뉴를 출력합니다. (화면 clear 포함)
    void DrawTitle();

    // 구분선 한 줄.  Line()      → ====...  56칸
    //                Line('-')   → ----...  56칸
    //                Line('-',30)→ ----...  30칸
    // 인자에 기본값이 있으므로 생략 가능합니다.
    // ★ 기본값은 선언부(여기)에만 씁니다. UI.cpp 에 또 쓰면 컴파일 에러입니다.
    void Line(char ch = '=', int width = 56);

    // 제목이 있는 머리말 블록을 출력합니다.
    //   Header("메 인 메 뉴") 결과:
    //     ========================================================
    //                   < 메 인 메 뉴 >
    //     --------------------------------------------------------
    void Header(const std::string& title);

    // 문자열 한 줄 출력 + 줄바꿈.
    // const std::string& (참조) 로 받는 이유: 문자열 복사 비용을 없애기 위함.
    void Print(const std::string& text);

    // 로그 한 줄 출력. 앞에 공백 2칸이 붙어 본문과 구분됩니다.
    // 전투 로그처럼 여러 줄 나열할 때 사용하세요.
    void PrintLog(const std::string& text);

    // ------------------------------------------------------------------
    //  입력  (★ 입력은 반드시 이 두 함수로만 받으세요 ★)
    // ------------------------------------------------------------------

    // 숫자 메뉴 선택을 받습니다. minV ~ maxV 범위 밖이거나
    // 문자를 입력하면 안내 후 다시 물어봅니다. 올바른 값이 나올 때까지 반복.
    //   사용: int c = UI::AskChoice(0, 3);
    int AskChoice(int minV, int maxV);

    // 이름을 입력받습니다. 빈 입력과 공백만 입력한 경우를 걸러냅니다.
    // (테스트케이스 "이름 공백 입력 - Abnormal" 항목 대응)
    std::string AskName();

    // "계속하려면 Enter..." 출력 후 대기합니다.
    void Pause();

} // namespace UI